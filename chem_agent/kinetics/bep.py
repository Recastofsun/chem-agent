"""Соотношение Белла-Эванса-Поляни (BEP) для серии родственных реакций, катализ (W-10, заготовка).

Ea = α·ΔH + β, α в [0, 1] (положение переходного состояния), β - внутренний барьер, кДж/моль.
Ea ограничен снизу нулем и снизу ΔH для эндотермических реакций (барьер не меньше теплового эффекта).
Параметры α, β задаются пользователем: универсальных значений нет (зависят от семейства реакций и
поверхности катализатора).
"""
from __future__ import annotations


def barrier(alpha: float, beta_kJ_mol: float, dH_kJ_mol: float) -> float:
    if not 0.0 <= alpha <= 1.0:
        raise ValueError("alpha в диапазоне [0, 1]")
    return max(alpha * dH_kJ_mol + beta_kJ_mol, dH_kJ_mol, 0.0)
